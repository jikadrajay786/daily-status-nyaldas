const DICTS: Record<Lang, Dict> = { en, hi, gu }

export type Vars = Record<string, string | number>
export type T = (key: Key, vars?: Vars) => string

export const translator =
  (lang: Lang): T =>
  (key, vars = {}) =>
    DICTS[lang][key].replace(/\{(\w+)\}/g, (m, k: string) => String(vars[k] ?? m))

export const LANG_LIST = ['en', 'hi', 'gu'] as const satisfies readonly Lang[]

export const isLang = (s: unknown): s is Lang => typeof s === 'string' && s in LANGS

export type I18n = { lang: Lang; locale: string; t: T; setLang: (l: Lang) => void }
export const I18nContext = createContext<I18n | null>(null)

export const useT = (): I18n => {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useT must be used inside I18nContext')
  return ctx
}
