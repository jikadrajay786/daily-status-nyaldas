import { describe, expect, it } from 'vitest'
import { channelOf, PUSH_EVENTS, pushData, pushServerConfig, pushText } from '../src/push'

describe('push data', () => {
  const id = '6f1c2a4e-8b7d-4c3a-9e21-5d4f3a2b1c0d'

  it('reads what the notify function sends', () => {
    expect(pushData({ event: 'taskAssigned', kind: 'task', id })).toEqual({
      event: 'taskAssigned',
      kind: 'task',
      id
    })
  })

  it('ignores anything else, so a stray push never navigates', () => {
    expect(pushData(null)).toBeNull()
    expect(pushData({})).toBeNull()
    expect(pushData({ event: 'deleteAll', kind: 'task', id })).toBeNull()
    expect(pushData({ event: 'comment', kind: 'profile', id })).toBeNull()
    expect(pushData({ event: 'comment', kind: 'status', id: 42 })).toBeNull()
  })

  it('gives every event an Android channel', () => {
    expect(PUSH_EVENTS.every((e) => channelOf[e])).toBe(true)
  })

  it("writes the notify function's messages", async () => {
    const src = `// Generated by packages/core/test/push.test.ts from core push.ts and the i18n dictionaries.
// Edit those, then run \`npx vitest -u\` in packages/core.
export const PUSH = ${JSON.stringify(pushServerConfig(), null, 2)} as const
`
    await expect(src).toMatchFileSnapshot('../../../supabase/functions/notify/messages.gen.ts')
  })

  it("words desktop alerts like the pushes, in the reader's language", () => {
    expect(pushText({ event: 'taskAssigned', vars: { text: 'Count stock' } }, 'en')).toEqual({
      title: 'New task for you',
      body: 'Count stock'
    })
    expect(
      pushText(
        { event: 'taskStatus', vars: { name: 'Jay', title: 'Count stock', status: 'completed' } },
        'hi'
      )
    ).toEqual({ title: 'Jay ने काम अपडेट किया', body: 'Count stock: हो गया' })
    expect(
      pushText({ event: 'statusSubmitted', vars: { name: 'Jay', text: '  Did   it ' } }, 'en')?.body
    ).toBe('Did it')
    expect(pushText({ event: 'somethingNew', vars: {} }, 'en')).toBeNull()
  })
})
